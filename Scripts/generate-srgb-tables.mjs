#!/usr/bin/env bun
// Writes Sources/BlurHashCore/SRGBTables.swift: the two sRGB transfer tables the codec uses instead of `pow`, which
// Embedded Swift has no library for. Both follow the BlurHash specification's formulas exactly, in double precision:
//
//   sRGBToLinear(b) = v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ^ 2.4,          v = b / 255
//   linearTosRGB(v) = trunc(v <= 0.0031308 ? v * 12.92 * 255 + 0.5 : (1.055 * v ^ (1 / 2.4) - 0.055) * 255 + 0.5)
//
// `linearFromByte[b]` is sRGBToLinear(b). `byteThresholds[b]` is the smallest double v with linearTosRGB(v) > b, found by
// bisection over the bit patterns of the doubles in 0...1 (they are ordered like the values), so counting the
// thresholds <= v gives linearTosRGB(v) for every double, bit for bit.
//
// usage: bun Scripts/generate-srgb-tables.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const sRGBToLinear = (byte) => {
  const v = byte / 255;
  return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
};

const linearTosRGB = (value) => {
  const v = Math.max(0, Math.min(1, value));
  return v <= 0.0031308 ? Math.trunc(v * 12.92 * 255 + 0.5) : Math.trunc((1.055 * Math.pow(v, 1 / 2.4) - 0.055) * 255 + 0.5);
};

const bits = new BigUint64Array(1);
const value = new Float64Array(bits.buffer);
const doubleOf = (pattern) => {
  bits[0] = pattern;
  return value[0];
};
value[0] = 1;
const one = bits[0];

/** The smallest double v in 0...1 with linearTosRGB(v) > byte. */
function threshold(byte) {
  let low = 0n;
  let high = one;
  while (low < high) {
    const middle = (low + high) / 2n;
    if (linearTosRGB(doubleOf(middle)) > byte) high = middle;
    else low = middle + 1n;
  }
  return doubleOf(low);
}

// JavaScript prints the shortest decimal that reads back as the same double, and Swift reads a literal to the nearest
// double, so the tables round-trip exactly.
const rows = (values) => {
  const lines = [];
  for (let start = 0; start < values.length; start += 4) {
    lines.push("    " + values.slice(start, start + 4).map((v) => (Number.isInteger(v) ? v.toFixed(1) : String(v))).join(", ") + ",");
  }
  return lines.join("\n");
};

const linear = Array.from({ length: 256 }, (_, byte) => sRGBToLinear(byte));
const thresholds = Array.from({ length: 255 }, (_, byte) => threshold(byte));

const source = `// Generated by Scripts/generate-srgb-tables.mjs; do not edit. Tests/BlurHashCoreTests/SRGBTests.swift checks both
// tables against the formulas of the specification evaluated with the platform's \`pow\`.

/// The sRGB transfer function as tables, so the codec needs no \`pow\`.
enum SRGB {
  /// The linear intensity of every 8-bit sRGB value.
  static let linearFromByte: [Double] = [
${rows(linear)}
  ]

  /// \`byteThresholds[b]\` is the smallest linear intensity that rounds to an sRGB byte above \`b\`.
  static let byteThresholds: [Double] = [
${rows(thresholds)}
  ]
}
`;

const output = join(import.meta.dir, "..", "Sources", "BlurHashCore", "SRGBTables.swift");
writeFileSync(output, source);
console.log(`wrote ${output}`);
